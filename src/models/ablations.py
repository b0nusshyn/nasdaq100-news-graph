"""Ablations and the ladder across seeds (task 3.9, #41). Owner: Modelling.

Trains, at seeds 42/43/44, the LSTM ladder (Baseline 5, Baseline 6, proposed) and six ablations
of the proposed model, all at the tuned config (3.12), and reports test within-day AUC (the
headline) as mean and seed range, so every difference sits next to the seed noise floor.

- **Edges:** drop `sector`, `comention` or `corr` in turn, and drop only the deal-arbitrage
  `corr` pairs (`deal_arb`, see `src.models.train.DEAL_ARB_PAIRS`).
- **News, signal vs structure:** a 2x2 with `sector` and `corr` held fixed. News features
  (sentiment, confidence, embeddings, `has_news`) on or off, crossed with `comention` edges
  (built from news co-mentions) on or off.

Seed 42 is the official run: the ablations write `predictions/gat_lstm_no_<what>.parquet` plus a
run record, and the ladder's seed-42 scores are read from the files `src.models.train` wrote.
Seeds 43 and 44 are scored in memory. Every (model, seed, horizon, fold) score is appended to
`results/tables/ablations_3_9.jsonl` as it finishes, so an interrupted run resumes.

    python -m src.models.ablations            # everything, resuming from the log
    python -m src.models.ablations --report   # rebuild results/tables/ablations_3_9.md from the log
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

SEEDS = (42, 43, 44)
OFFICIAL_SEED = 42
LADDER = {"B5 LSTM price": ("lstm_price", ()), "B6 LSTM + news": ("lstm_news", ()),
          "proposed": ("gat_lstm", ())}
ABLATIONS = {
    "drop sector": ("gat_lstm", ("sector",)),
    "drop comention": ("gat_lstm", ("comention",)),
    "drop corr": ("gat_lstm", ("corr",)),
    "drop deal-arb corr pairs": ("gat_lstm", ("deal_arb",)),
    "drop news features": ("gat_lstm", ("news",)),
    "drop news features and comention": ("gat_lstm", ("comention", "news")),
}
VARIANTS = LADDER | ABLATIONS
# The 2x2 (sector + corr always present): (news features, comention edges) -> variant
NEWS_GRID = {(True, True): "proposed", (True, False): "drop comention",
             (False, True): "drop news features", (False, False): "drop news features and comention"}
EDGE_ROWS = ("drop sector", "drop comention", "drop corr", "drop deal-arb corr pairs")


def fold_scores(preds: pd.DataFrame) -> list[dict]:
    """Within-day AUC (headline), fold AUC and timing AUC per (horizon, fold)."""
    from src.models.ladder_report import auc, timing_auc, within_day_auc

    return [{"horizon": int(h), "fold": int(f), "within_day_auc": within_day_auc(g),
             "auc": auc(g["y_true"], g["p_up"]), "timing_auc": timing_auc(g)}
            for (h, f), g in preds.groupby(["horizon", "fold"])]


def read_log(path: Path) -> pd.DataFrame:
    if not path.exists():
        return pd.DataFrame(columns=["variant", "seed", "horizon", "fold"])
    return pd.DataFrame([json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line])


def per_seed(log: pd.DataFrame, metric: str = "within_day_auc") -> pd.DataFrame:
    """Mean over folds, per (variant, horizon) row and seed column."""
    return log.groupby(["variant", "horizon", "seed"])[metric].mean().unstack("seed")


def cell(row: pd.Series) -> str:
    """'mean (min to max)' across seeds."""
    return f"{row.mean():.3f} ({row.min():.3f} to {row.max():.3f})"


def delta_cell(a: pd.Series, b: pd.Series, fold_d: pd.Series | None = None) -> str:
    """Seed-paired difference a - b: mean, range, and in how many seeds it is positive.

    `fold_d`, the same difference per (seed, fold), adds how many fold-seeds are positive: a
    seed-level count can be carried by a single fold.
    """
    d = a - b
    out = f"{d.mean():+.4f} ({d.min():+.4f} to {d.max():+.4f}; > 0 in {(d > 0).sum()}/{len(d)} seeds"
    if fold_d is not None:
        out += f", {(fold_d > 0).sum()}/{len(fold_d)} fold-seeds"
    return out + ")"


def report(log: pd.DataFrame) -> str:
    from src.graph.comention_report import md

    s = per_seed(log)
    seeds = list(s.columns)
    folds = log.groupby(["variant", "seed", "horizon"])["fold"].nunique()
    lines = [
        "# Ablations and the ladder across seeds (task 3.9, #41)",
        "",
        "Generated by `python -m src.models.ablations`. Test **within-day AUC** (the headline), mean over the 5 "
        f"walk-forward folds, at seeds {', '.join(map(str, seeds))}; each cell is `mean (min to max)` across "
        "seeds. All models use the tuned config (3.12, T1). Seed 42 is the official run behind the prediction "
        "files. Folds share training data (adjacent folds 75%), so fold counts mean *consistent*, not *replicated*.",
    ]
    if (folds < 5).any():
        lines += ["", f"**Incomplete:** {', '.join(f'{v} seed {sd} {h}d' for (v, sd, h) in folds[folds < 5].index)}"]
    for h in sorted(log["horizon"].unique()):
        sh = s.xs(h, level="horizon")
        prop = sh.loc["proposed"]
        wh = log[log["horizon"] == h].pivot_table(index=["seed", "fold"], columns="variant", values="within_day_auc")

        def step(a: str, b: str, sh=sh, wh=wh) -> str:
            return delta_cell(sh.loc[a], sh.loc[b], wh[a] - wh[b])

        lines += ["", f"## {h} day{'s' if h > 1 else ''}", "", "### Ladder", ""]
        rows = [{"model": v, **{f"seed {sd}": sh.loc[v, sd] for sd in seeds}, "mean (range)": cell(sh.loc[v])}
                for v in LADDER if v in sh.index]
        lines.append(md(pd.DataFrame(rows), index=False, digits=3))
        if {"B5 LSTM price", "B6 LSTM + news", "proposed"} <= set(sh.index):
            lines += [
                "",
                f"- news step (B6 - B5): {step('B6 LSTM + news', 'B5 LSTM price')}",
                f"- graph step (proposed - B6): {step('proposed', 'B6 LSTM + news')}",
                f"- seed noise floor: the proposed model's seed range is {prop.max() - prop.min():.4f}",
            ]
            mono = monotone_folds(log, h)
            lines.append("- ladder monotone (both steps > 0) in " + ", ".join(
                f"{n}/5 folds at seed {sd}" for sd, n in mono.items()))
            by_fold = pd.DataFrame({
                "news step (B6 - B5)": wh["B6 LSTM + news"] - wh["B5 LSTM price"],
                "graph step (proposed - B6)": wh["proposed"] - wh["B6 LSTM + news"],
            }).groupby(level="fold").mean().T
            lines += ["", "Each step by fold, mean over seeds:", "",
                      md(by_fold.rename(columns=lambda f: f"fold {f}").reset_index(names="step"),
                         index=False, digits=4)]
        if all(v in sh.index for v in NEWS_GRID.values()):
            g = {k: sh.loc[v] for k, v in NEWS_GRID.items()}
            lines += [
                "", "### News: signal vs structure", "",
                "`sector` and `corr` edges are present in every cell. Baseline 6 (news features, no graph at all) "
                "and Baseline 5 are the no-graph references above.", "",
                "| | comention edges | no comention edges |", "|---|---|---|",
                f"| **news features** | {cell(g[True, True])} (proposed) | {cell(g[True, False])} |",
                f"| **no news features** | {cell(g[False, True])} | {cell(g[False, False])} |",
                "",
                f"- signal only vs structure only: {step(NEWS_GRID[True, False], NEWS_GRID[False, True])}",
                f"- news features, with comention present: {step(NEWS_GRID[True, True], NEWS_GRID[False, True])}",
                f"- news features, without comention: {step(NEWS_GRID[True, False], NEWS_GRID[False, False])}",
                f"- comention edges, with news features: {step(NEWS_GRID[True, True], NEWS_GRID[True, False])}",
                f"- comention edges, without news features: {step(NEWS_GRID[False, True], NEWS_GRID[False, False])}",
            ]
        present = [v for v in EDGE_ROWS if v in sh.index]
        if present:
            lines += ["", "### Edges", "",
                      "Change from the proposed model, paired by seed. Negative means the dropped edges were helping.",
                      "", "| ablation | within-day AUC | change vs proposed |", "|---|---|---|"]
            lines += [f"| {v} | {cell(sh.loc[v])} | {step(v, 'proposed')} |" for v in present]
            if "drop deal-arb corr pairs" in present:
                d = (wh["drop deal-arb corr pairs"] - wh["proposed"]).abs().max()
                lines += ["", "The deal-arbitrage pairs are 4 to 6 of each fold's `corr` edges. Dropping them changes "
                          f"within-day AUC by at most {d:.4f} in any fold-seed: no measurable effect."]
    lines += ["", "## Fold AUC (diagnostic)", "",
              "Mean over folds, `mean (min to max)` across seeds; includes market timing.", "",
              "| variant | " + " | ".join(f"{h}d" for h in sorted(log["horizon"].unique())) + " |",
              "|---|" + "---|" * log["horizon"].nunique()]
    fa = per_seed(log, "auc")
    for v in VARIANTS:
        if v in fa.index.get_level_values("variant"):
            lines.append(f"| {v} | " + " | ".join(cell(fa.loc[(v, h)]) for h in sorted(log["horizon"].unique())) + " |")
    return "\n".join(lines)


def monotone_folds(log: pd.DataFrame, h: int) -> dict[int, int]:
    w = log[log["horizon"] == h].pivot_table(index=["seed", "fold"], columns="variant", values="within_day_auc")
    ok = (w["B6 LSTM + news"] > w["B5 LSTM price"]) & (w["proposed"] > w["B6 LSTM + news"])
    return ok.groupby(level="seed").sum().astype(int).to_dict()


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--report", action="store_true", help="rebuild the table from the log; train nothing")
    p.add_argument("--seeds", type=int, nargs="+", default=list(SEEDS))
    args = p.parse_args()

    from src.core.paths import RESULTS_DIR

    out_dir = RESULTS_DIR / "tables"
    log_path = out_dir / "ablations_3_9.jsonl"
    if not args.report:
        run(args.seeds, log_path)
    text = report(read_log(log_path))
    (out_dir / "ablations_3_9.md").write_text(text + "\n", encoding="utf-8")
    print(text)


def run(seeds, log_path: Path) -> None:
    import time

    from src.core.config import load_config
    from src.core.io import read_predictions, read_table, write_predictions
    from src.core.paths import CONFIGS_DIR, predictions_path
    from src.models.panel import load_panel
    from src.models.train import folds_for, model_name, train_fold, write_run_record

    log = read_log(log_path)
    done = set(zip(log["variant"], log["seed"], strict=True)) if len(log) else set()
    panel, edges = load_panel(), read_table("edges")
    folds = folds_for(panel)
    log_path.parent.mkdir(parents=True, exist_ok=True)
    for seed in seeds:
        for variant, (base, ablate) in VARIANTS.items():
            if (variant, seed) in done:
                continue
            cfg = load_config(CONFIGS_DIR / f"{base}.yaml")
            name = model_name(ablate, cfg.get("model", base))
            t0 = time.perf_counter()
            if seed == OFFICIAL_SEED and variant in LADDER:
                # Written by src.models.train at the tuned config; refuse a stale file.
                record = json.loads(predictions_path(name).with_name(f"{name}_run.json").read_text(encoding="utf-8"))
                if record["config"] != cfg:
                    raise ValueError(f"{name}.parquet was not trained with configs/{base}.yaml: rerun src.models.train")
                preds, source = read_predictions(name), "file"
            else:
                cfg = cfg | {"seed": seed}
                parts, infos = [], []
                for h in cfg["horizons"]:
                    for fold in folds:
                        pr, info = train_fold(panel, edges, fold, h, cfg, ablate=ablate, log=lambda *_: None)
                        parts.append(pr)
                        infos.append(info)
                preds, source = pd.concat(parts, ignore_index=True), "trained"
                if seed == OFFICIAL_SEED:
                    path = write_predictions(preds, name)
                    write_run_record(path, cfg, ablate, infos)
                    source = f"trained, wrote {path.name}"
            rows = [{"variant": variant, "model": name, "ablate": list(ablate), "seed": seed, **r}
                    for r in fold_scores(preds)]
            with log_path.open("a", encoding="utf-8") as f:
                f.writelines(json.dumps(r) + "\n" for r in rows)
            wd = {h: np.mean([r["within_day_auc"] for r in rows if r["horizon"] == h]) for h in (1, 5)}
            print(f"seed {seed} {variant}: within-day AUC 1d {wd[1]:.3f}, 5d {wd[5]:.3f} "
                  f"({(time.perf_counter() - t0) / 60:.1f} min, {source})", flush=True)


if __name__ == "__main__":
    main()
