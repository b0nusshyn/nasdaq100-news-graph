"""Fine-tuning pass for the proposed model (task 3.12, #58). Owner: Modelling.

Trains every config in `GRID` on every walk-forward fold and both horizons, scores each on the
**validation split inside its training fold** (the test windows are never predicted), and picks
one shared config for both horizons by mean validation within-day AUC, the headline metric.
Writes `results/tables/tuning_gat_lstm.md`; every fold-horizon is appended to
`results/tables/tuning_gat_lstm.jsonl` as soon as it finishes, so an interrupted sweep resumes.

    python -m src.models.tune                  # whole grid, resuming from the log
    python -m src.models.tune --only T0 T2     # a subset
    python -m src.models.tune --report         # rebuild the table from the log, train nothing
"""

from __future__ import annotations

import argparse
import copy
import json
from pathlib import Path

import pandas as pd

# The user's plan (16 and 18 Nov): the epoch-1 stop was a step-count problem (14 steps per epoch
# at batch_days 32), so sweep batch_days down to 8 with lower learning rates and more epochs.
# T0 is the 3.8 training setup under the new stopping rule, as the reference.
COMMON = {"epochs": 40, "early_stopping_patience": 4, "validate_every_steps": 14,
          "early_stopping_metric": "within_day_auc"}
GRID = {
    "T0": {"batch_days": 32, "lr": 1e-3},
    "T1": {"batch_days": 8, "lr": 1e-3},
    "T2": {"batch_days": 8, "lr": 3e-4},
    "T3": {"batch_days": 8, "lr": 1e-4},
    "T4": {"batch_days": 16, "lr": 3e-4},
    "T5": {"batch_days": 8, "lr": 3e-4, "dropout": 0.3},
}
ENCODER_KEYS = ("hidden", "dropout", "layers")
GAT_KEYS = ("heads",)


def config_for(base: dict, overrides: dict) -> dict:
    """`base` with the grid entry's overrides placed in the right block."""
    cfg = copy.deepcopy(base)
    for k, v in overrides.items():
        block = "encoder" if k in ENCODER_KEYS else "gat" if k in GAT_KEYS else "train"
        cfg[block][k] = v
    cfg["train"] |= {k: v for k, v in COMMON.items() if k not in overrides}
    return cfg


def done(log_path: Path) -> pd.DataFrame:
    if not log_path.exists():
        return pd.DataFrame()
    return pd.DataFrame([json.loads(line) for line in log_path.read_text(encoding="utf-8").splitlines() if line])


def summarize(runs: pd.DataFrame) -> tuple[pd.DataFrame, str]:
    """One row per config (mean over folds), and the chosen shared config."""
    by = runs.groupby(["config", "horizon"])
    per_h = by["best_val_within_day_auc"].mean().unstack("horizon")
    t = pd.DataFrame({
        "batch_days": runs.groupby("config")["batch_days"].first(),
        "lr": runs.groupby("config")["lr"].first(),
        "hidden": runs.groupby("config")["hidden"].first(),
        "heads": runs.groupby("config")["heads"].first(),
        "dropout": runs.groupby("config")["dropout"].first(),
        "val within-day AUC 1d": per_h[1], "val within-day AUC 5d": per_h[5],
    })
    t["val within-day AUC (mean)"] = t[["val within-day AUC 1d", "val within-day AUC 5d"]].mean(axis=1)
    t["val MCC (mean)"] = runs.groupby("config")["val_mcc"].mean()
    t["val within-day AUC at loss optimum"] = runs.groupby("config")["val_within_day_auc_at_loss_optimum"].mean()
    t["best step (median)"] = runs.groupby("config")["best_step"].median()
    t["loss-optimal step (median)"] = runs.groupby("config")["loss_optimal_step"].median()
    t["minutes"] = runs.groupby("config")["seconds"].sum() / 60
    complete = runs.groupby("config").size() == runs.groupby("config").size().max()
    winner = t.loc[complete[complete].index, "val within-day AUC (mean)"].idxmax()
    return t, winner


def report(runs: pd.DataFrame) -> str:
    from src.graph.comention_report import md

    t, winner = summarize(runs)
    shown = t.reset_index(names="config").astype({"batch_days": int, "hidden": int, "heads": int,
                                                  "best step (median)": int, "loss-optimal step (median)": int})
    shown["lr"] = shown["lr"].map(lambda v: f"{v:.0e}")
    shown["dropout"] = shown["dropout"].map(lambda v: f"{v:.1f}")
    ranked = t["val within-day AUC (mean)"].sort_values(ascending=False)
    lines = [
        "# Fine-tuning pass, GAT + LSTM (task 3.12, #58)",
        "",
        "Generated by `python -m src.models.tune`. Every score is on the **validation split inside each "
        "training fold** (last 10% of the training days, after the 5-day embargo); the test windows are "
        "never predicted. Means over the 5 folds. Selection: one shared config for both horizons, the "
        "highest mean validation within-day AUC (the headline metric). Early stopping keeps the checkpoint "
        "with the best validation within-day AUC; `loss-optimal step` is where validation loss bottomed, "
        "logged to measure how far the two criteria disagree.",
        "",
        md(shown, index=False, digits=4),
        "",
        f"**Chosen shared config: {winner}** (val within-day AUC {t.loc[winner, 'val within-day AUC (mean)']:.4f}; "
        f"runner-up {ranked.index[1]} {ranked.iloc[1]:.4f}, {ranked.iloc[0] - ranked.iloc[1]:+.4f}). Each "
        "score is the best of many validation checks on the same ~50 days per fold, so it is optimistic, and "
        "more so for configs that ran more checks; margins this small are within selection noise.",
        "",
        "Each horizon's own best, and how far the shared config sits from it:",
        "",
    ]
    for h in (1, 5):
        col = f"val within-day AUC {h}d"
        own = t[col].idxmax()
        lines.append(f"- {h}d: own best {own} ({t.loc[own, col]:.4f}); shared {winner} "
                     f"{t.loc[winner, col]:.4f} ({t.loc[winner, col] - t.loc[own, col]:+.4f})")
    gap = runs.assign(gap=runs["best_step"] - runs["loss_optimal_step"])
    lines += [
        "",
        "Stopping criteria, per fold-horizon (all configs): within-day-AUC-optimal step minus loss-optimal step.",
        "",
        f"- median gap {gap['gap'].median():+.0f} steps; |gap| > 1 epoch in "
        f"{(gap['gap'].abs() > gap['steps_per_epoch']).sum()}/{len(gap)} fold-horizons",
        f"- mean val within-day AUC: {gap['best_val_within_day_auc'].mean():.4f} at the AUC optimum vs "
        f"{gap['val_within_day_auc_at_loss_optimum'].mean():.4f} at the loss optimum. The first is a maximum "
        "over the same checks, so it is higher by construction; the step gap is the evidence that the two "
        "criteria pick different checkpoints, not the AUC difference.",
    ]
    return "\n".join(lines)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--only", nargs="+", default=None, help="config ids from GRID")
    p.add_argument("--report", action="store_true", help="rebuild the table from the log; train nothing")
    args = p.parse_args()

    from src.core.paths import RESULTS_DIR

    out_dir = RESULTS_DIR / "tables"
    log_path = out_dir / "tuning_gat_lstm.jsonl"
    if not args.report:
        from src.core.config import load_config
        from src.core.io import read_table
        from src.core.paths import CONFIGS_DIR
        from src.models.panel import load_panel
        from src.models.train import folds_for, train_fold

        base = load_config(CONFIGS_DIR / "gat_lstm.yaml")
        panel, edges = load_panel(), read_table("edges")
        folds = folds_for(panel)
        prev = done(log_path)
        seen = set() if prev.empty else set(zip(prev["config"], prev["horizon"], prev["fold"], strict=True))
        out_dir.mkdir(parents=True, exist_ok=True)
        for cid in args.only or GRID:
            cfg = config_for(base, GRID[cid])
            for h in cfg["horizons"]:
                for fold in folds:
                    if (cid, h, fold.index) in seen:
                        continue
                    _, info = train_fold(panel, edges, fold, h, cfg, predict_test=False, log=lambda *_: None)
                    row = {"config": cid, "batch_days": cfg["train"]["batch_days"], "lr": cfg["train"]["lr"],
                           "hidden": cfg["encoder"]["hidden"], "heads": cfg["gat"]["heads"],
                           "dropout": cfg["encoder"]["dropout"], **info}
                    with log_path.open("a", encoding="utf-8") as f:
                        f.write(json.dumps(row, default=str) + "\n")
                    print(f"{cid} h={h} fold {fold.index}: {info['seconds'] / 60:.1f} min, {info['steps']} steps "
                          f"(best {info['best_step']}, loss-optimal {info['loss_optimal_step']}) | val within-day AUC "
                          f"{info['best_val_within_day_auc']:.4f} (at loss optimum "
                          f"{info['val_within_day_auc_at_loss_optimum']:.4f}), val MCC {info['val_mcc']:.3f}",
                          flush=True)
    text = report(done(log_path))
    (out_dir / "tuning_gat_lstm.md").write_text(text + "\n", encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
