"""Return-correlation measurement report. Owner: Modelling. Issue #22 (task 3.4).

The evidence behind SCHEMA.md decision 7 (partial correlation given the equal-weight market,
min_overlap = 126, top-k = 10). Reads `prices`, builds the shared walk-forward folds, and writes:

- `results/tables/corr_report.md`: tickers left without `corr` edges by min_overlap, graph
  density, the weight distribution of selected edges, overlap with `sector` edges, and top
  pairs, each for residual and raw returns.
- `results/tables/corr_top_pairs.csv`: each fold's 20 strongest `corr` edges at the SCHEMA.md
  defaults, in the same shape as `comention_top_pairs.csv`.

    python -m src.graph.corr_report --output results/tables
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from src.core.paths import RESULTS_DIR
from src.graph.comention_report import degree_row, md, shared_folds

TREATMENTS = {"residual": {"residual": True}, "raw": {"residual": False}}
OVERLAPS = (20, 60, 126)


def build(prices: pd.DataFrame, cfg: dict | None = None, *, min_overlap: int | None = None) -> tuple[str, pd.DataFrame]:
    """Report text and top pairs. `cfg` defaults to `configs/walk_forward.yaml`; `min_overlap`
    to SCHEMA.md's (both overridable so the report also runs on the short test fixtures)."""
    from src.core.schema import CORR_MIN_OVERLAP, CORR_TOP_K
    from src.graph.build_edges import corr_edges, corr_pairs, load_gics, market_model, sector_edges

    min_overlap = CORR_MIN_OVERLAP if min_overlap is None else min_overlap
    folds = shared_folds(prices, cfg)
    betas = {f.index: market_model(prices, f.train)[1] for f in folds}
    out = [
        "# Return-correlation edges: measurements (task 3.4, #22)",
        "",
        "Generated by `python -m src.graph.corr_report`. Evidence for SCHEMA.md decision 7. "
        "Candidates are the tickers in the index on at least one training day; each uses every "
        "training-window return it has. `residual` is the partial correlation given the "
        "equal-weight market (beta fitted per stock per fold); `raw` correlates raw returns. "
        "Share classes of one company never pair.",
        "",
        "| fold | training window | days | candidates | market beta p10 – p90 |",
        "|---|---|---|---|---|",
        *(f"| {f.index} | {f.train[0]:%Y-%m-%d} → {f.train[-1]:%Y-%m-%d} | {len(f.train)} | "
          f"{len(betas[f.index])} | {betas[f.index].quantile(0.1):.2f} – {betas[f.index].quantile(0.9):.2f} |"
          for f in folds),
    ]

    stats = {(f.index, name): corr_pairs(prices, f.train, **kw) for f in folds for name, kw in TREATMENTS.items()}

    rows = {}
    for f in folds:
        p, n = stats[f.index, "residual"], len(betas[f.index])
        for m in OVERLAPS:
            kept = p[p["n_obs"] >= m]
            lost = n - len(set(kept["a"]) | set(kept["b"]))
            rows.setdefault(f.index, {})[f"lost at {m}"] = f"{lost} ({100 * lost / n:.1f}%)" if n else "0"
    out += ["", "## 1 · Tickers left without corr edges, by min_overlap", "",
            "A candidate loses all `corr` edges when no peer shares `min_overlap` training-day returns "
            "with it. Such tickers keep their `sector` and `comention` edges.", "",
            md(pd.DataFrame(rows).T.rename_axis("fold"))]

    edges = {name: corr_edges(prices, folds, min_overlap=min_overlap, **kw) for name, kw in TREATMENTS.items()}
    out += ["", f"## 2 · Density after top-k (min_overlap {min_overlap}, top_k {CORR_TOP_K})"]
    for name, e in edges.items():
        rows = {f.index: degree_row(e[e["fold"] == f.index]) for f in folds}
        out += ["", f"**{name}**", "", md(pd.DataFrame(rows).T.rename_axis("fold"))]

    out += ["", "## 3 · Weight of selected edges", "",
            "Distribution over every selected edge, not just each ticker's 10th peer."]
    for name, e in edges.items():
        und = e[e["src"] < e["dst"]]
        t = und.groupby("fold")["weight"].describe(percentiles=[0.1, 0.5, 0.9])
        t = t.reindex([f.index for f in folds])[["count", "min", "10%", "50%", "90%", "max"]]
        t = t.rename(columns={"count": "edges"}).fillna({"edges": 0}).astype({"edges": int})
        out += ["", f"**{name}**", "", md(t, digits=2)]

    sector = sector_edges(load_gics())
    sector_pairs = set(zip(sector["src"], sector["dst"], strict=True))
    rows = {}
    for name, e in edges.items():
        for f in folds:
            mine = e[e["fold"] == f.index]
            shared = sum(p in sector_pairs for p in zip(mine["src"], mine["dst"], strict=True))
            rows.setdefault(f.index, {})[name] = f"{100 * shared / len(mine):.0f}%" if len(mine) else ""
    out += ["", "## 4 · Overlap with sector edges", "",
            "Share of `corr` edges that are also `sector` edges (same GICS industry).", "",
            md(pd.DataFrame(rows).T.rename_axis("fold"))]

    if folds:
        last = folds[-1].index
        cols = ["a", "b", "n_obs", "corr"]
        out += ["", f"## 5 · Top 15 pairs, fold {last}: residual vs raw"]
        for name in TREATMENTS:
            p = stats[last, name]
            p = p[p["n_obs"] >= min_overlap]
            out += ["", f"**{name}**", "", md(p.nlargest(15, "corr")[cols], index=False, digits=3)]
    out.append("")

    und = edges["residual"][edges["residual"]["src"] < edges["residual"]["dst"]]
    top = und.sort_values(["fold", "weight"], ascending=[True, False]).groupby("fold").head(20)
    return "\n".join(out), top[["fold", "src", "dst", "weight"]].reset_index(drop=True)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--output", type=Path, default=RESULTS_DIR / "tables", help="directory for the report files")
    args = p.parse_args()

    from src.core.io import read_table

    report, top = build(read_table("prices", columns=["date", "ticker", "close", "in_index"]))
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "corr_report.md").write_text(report + "\n", encoding="utf-8")
    top.to_csv(args.output / "corr_top_pairs.csv", index=False, float_format="%.4f")
    print(f"wrote {args.output / 'corr_report.md'} and corr_top_pairs.csv")


if __name__ == "__main__":
    main()
